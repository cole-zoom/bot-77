"""Load times for the simulator engine from the game client's own logic tables -> the fork's include/core/LoadTimes.h
(2026-10-29, sim fidelity; replaces scripts/sim_load_times.py's RoyaleAPI 2023 extract).

  uv run --no-sync python scripts/sim_load_times_client.py [--out path/to/LoadTimes.h]

Source: data/external/cr_client/logic (the installed client's tables, gitignored; Cole's 2026-10-28 exception for the
stat audit). Card -> unit as scripts/audit_client_stats.py does it; Evolutions and Heroes use their base card's unit
(the client keeps their changes in separate sections; their load time is the base unit's).

What the number means (RoyaleAPI, "The Secret Stats", and Supercell's "first hit speed" in the balance notes): a unit
loads LoadTime of its attack while it is not attacking (walking, deploying, idle); a loaded unit's first hit lands
HitSpeed - LoadTime after it starts attacking, later hits every HitSpeed. The engine applies that in
CombatEntity::update (include/entities/CombatEntity.h); this file only carries LoadTime per card, in ticks.
"""
import argparse
import csv
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from audit_client_stats import CLIENT_NAME, FIRST_LEVEL, LOGIC, UNIT_OF, UNIT_OVERRIDE, norm, units  # noqa: E402

from bot77.sim import cards as sc  # noqa: E402

ap = argparse.ArgumentParser()
ap.add_argument("--out", default="third_party/clash-royale-env/include/core/LoadTimes.h")
a = ap.parse_args()

chars, _ = units()
cards = {}
for r in csv.DictReader(open(LOGIC / "spells_characters.csv")):
    if r["Name"] and r["SummonCharacter"] and r["Rarity"] in FIRST_LEVEL:
        cards[norm(r["Name"])] = r
for f in ("spells_buildings.csv", "spells_hero_form.csv"):
    for r in csv.DictReader(open(LOGIC / f)):
        if r.get("Name") and r.get("SummonCharacter") and r.get("Rarity") in FIRST_LEVEL:
            cards.setdefault(norm(r["Name"]), r)
for r in csv.DictReader(open(LOGIC / "spells_characters.csv")):
    if r["Name"] and not r["SummonCharacter"] and r["Rarity"] in FIRST_LEVEL and r["Name"] in UNIT_OF:
        cards[norm(r["Name"])] = {**r, "SummonCharacter": UNIT_OF[r["Name"]]}

rows, missing, first, by_name, fh_rows = [], [], [], {}, []
info = sc.engine_cards()
for eid, c in sorted(info.items()):
    if c["is_spell"]:
        continue
    name = c["name"]
    base = name[5:] if c["is_hero"] and name.startswith("Hero ") else name
    card = cards.get(norm(base)) or cards.get(norm(CLIENT_NAME.get(base, "")))
    unit_name = UNIT_OVERRIDE.get(base, card["SummonCharacter"]) if card else None
    unit = chars.get(unit_name) if unit_name else None
    if unit is None:
        missing.append(f"{eid} {name}")
        continue
    lt, hs = int(unit.get("LoadTime", 0)), int(unit.get("HitSpeed", 0))
    tag = " (Evolution: base unit)" if c["evolution"] else (" (Hero: base unit)" if c["is_hero"] else "")
    rows.append((eid, int(lt / 100 + 0.5), f"{name}: {unit_name} LoadTime {lt} ms, HitSpeed {hs} ms{tag}"))
    # the first hit of a loaded unit: HitSpeed - LoadTime (none when the load is not shorter: Inferno, Mighty Miner)
    attacks = bool(unit.get("Damage") or unit.get("Projectile") or unit.get("CustomFirstProjectile")
                   or unit.get("AttackSequenceList"))
    # a unit that never hits (huts, Furnace, Elixir Collector: their HitSpeed is a spawn interval) has none
    fh = int((hs - lt) / 100 + 0.5) if hs > lt and attacks else -1
    fh_rows.append((eid, fh, f"{name}: {hs} - {lt} ms"))
    if not c["evolution"] and not c["is_hero"]:
        by_name.setdefault(name, fh)
    if unit.get("LoadFirstHit"):
        first.append((eid, f"{name}: {unit_name} LoadFirstHit"))

body = "\n".join(f"        case {eid}: return {t};  // {cmt}" for eid, t, cmt in rows)
fh_body = "\n".join(f"        case {eid}: return {t};  // {cmt}" for eid, t, cmt in fh_rows)
names = "\n".join(f'    if (name == "{n}") return {t};' for n, t in sorted(by_name.items()))
Path(a.out).write_text(f"""#pragma once
#include <string>

// Load time per card, in ticks (LoadTime ms / 100, rounded): how much of its attack a unit loads while it is not
// attacking. A loaded unit's first hit lands attackCooldown - loadTicks after it starts attacking; later hits
// follow attackCooldown (CombatEntity::update). Generated by bot-77's scripts/sim_load_times_client.py from the
// game client's logic tables (characters/*.toml, buildings.toml; 2026-10-29). Evolutions and Heroes use their
// base card's unit. Not matched (no entry, so no load): {', '.join(missing) or 'none'}.
inline int loadTicksForCard(int cardId) {{
    switch (cardId) {{
{body}
        default: return 0;
    }}
}}

// Units that must load before their first hit too (the client's LoadFirstHit: they spawn unloaded, and a stun
// empties the load). Everyone else spawns loaded.
inline bool loadFirstHitForCard(int cardId) {{
    switch (cardId) {{
{chr(10).join(f"        case {eid}: return true;  // {cmt}" for eid, cmt in first)}
        default: return false;
    }}
}}

// First hit of a loaded unit, in ticks: (HitSpeed - LoadTime) / 100, rounded, from the client's own HitSpeed (the
// engine's attackCooldown can differ, e.g. a kamikaze's). -1 = none (no entry, or a load not shorter than the hit
// speed: Inferno Tower / Dragon, Mighty Miner, whose load is their lock-on).
inline int firstHitTicksForCard(int cardId) {{
    switch (cardId) {{
{fh_body}
        default: return -1;
    }}
}}

// Bodies a card spawns (a Battle Ram's Barbarians, a Tombstone's Skeletons, ...) carry no card id: their first hit
// is the playable card of the same name's (the engine's card names). -1 = no such card.
inline int firstHitTicksForUnitName(const std::string& name) {{
{names}
    return -1;
}}
""")
print(f"{len(rows)} cards -> {a.out}; not matched: {missing}")
