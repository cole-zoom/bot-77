"""Which of our cards the simulator engine has (docs/simulator.md S1) -> docs/simulator-cards.md.

  uv run python scripts/sim_cards.py

Every card in our `cards` table and every (card, form) played in the human replays (`plays`, source hand), mapped
through bot77.sim.cards; what's missing, weighted by how often it is played.
"""
import collections
from pathlib import Path

import lancedb

from bot77.sim import cards as sc

db = lancedb.connect("data/lancedb")
human = {r["match_id"] for r in db.open_table("matches").search().where("source IN ('replay_tv', 'replay_bl')")
         .select(["match_id"]).limit(100_000).to_arrow().to_pylist()}
plays = [p for p in db.open_table("plays").search().where("source = 'hand' AND kind = 'play'")
         .select(["match_id", "card", "card_id", "form"]).limit(1_000_000).to_arrow().to_pylist()
         if p["match_id"] in human and p["card_id"]]
used = collections.Counter((p["card_id"], p["form"] or "normal") for p in plays)
total = sum(used.values())

ours = sc.our_cards()
missing_cards = sorted(n for i, n in ours.items() if sc.engine_id(i) is None and n not in sc.TOWER_TROOPS)
rows, fallback = [], []
for (cid, form), n in used.most_common():
    name = ours.get(cid, str(cid))
    if sc.engine_id(cid) is None:
        rows.append((name, form, n))
    elif sc.engine_id(cid, form) is None:
        fallback.append((name, form, n))

miss_n = sum(n for *_, n in rows)
fb_n = sum(n for *_, n in fallback)
out = [
    "# Simulator cards (generated by `scripts/sim_cards.py`)",
    "",
    f"Our `cards` table: {len(ours)} cards; the engine (ClashRoyaleEnv fork) has all but {len(missing_cards)} "
    f"(the 4 tower troops aside). Human replay plays: {total:,}.",
    "",
    "Mapped by name (`bot77.sim.cards`); a play's form picks the engine's Evolution or Hero id. Tower troops "
    "(Tower Princess, Cannoneer, Dagger Duchess, Royal Chef) are the engine's `TowerTroopType`, not cards.",
    "",
    "## Not in the engine",
    "",
    "| Card | Plays in human replays |",
    "|---|---|",
]
counts = collections.Counter()
for name, form, n in rows:
    counts[name] += n
for name in missing_cards:
    out.append(f"| {name} | {counts.get(name, 0):,} |")
out += [
    "",
    f"{miss_n:,} plays ({miss_n / total:.1%}) are of a card the engine lacks: a window containing one can't be "
    "replayed faithfully (S2 skips such windows).",
    "",
    "## Played form the engine lacks (falls back to the plain card)",
    "",
    "| Card | Form | Plays |",
    "|---|---|---|",
]
out += [f"| {name} | {form} | {n:,} |" for name, form, n in fallback]
out += ["", f"{fb_n:,} plays ({fb_n / total:.1%}) use a fallback."]
Path("docs/simulator-cards.md").write_text("\n".join(out) + "\n")
print("\n".join(out))
