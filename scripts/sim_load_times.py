"""First-hit delays (load times) for the simulator engine (docs/simulator.md S2) -> the fork's
include/core/LoadTimes.h, from RoyaleAPI's public cr-api-data (game-file extracts, last updated 2023-12;
royaleapi.github.io/cr-api-data).

  uv run python scripts/sim_load_times.py

The JSON is downloaded into data/external/cr-api-data/ (gitignored) and read as data only.
"""
import json
import re
import urllib.request
from pathlib import Path

from bot77.sim import cards as sc

SRC = "https://royaleapi.github.io/cr-api-data/json/"
DIR = Path("data/external/cr-api-data")
OUT = Path("third_party/clash-royale-env/include/core/LoadTimes.h")


def get(name: str):
    DIR.mkdir(parents=True, exist_ok=True)
    p = DIR / name
    if not p.exists():
        urllib.request.urlretrieve(SRC + name, p)
    return json.loads(p.read_text())


def norm(s: str) -> str:
    return re.sub(r"[^a-z]", "", (s or "").lower())


chars = {c["name"]: c for c in get("cards_stats_characters.json") + get("cards_stats_building.json")}
cards, buildings = {}, {}
for t in get("cards_stats_troop.json"):  # by the English card name, then the internal one
    cards.setdefault(norm(t.get("name_en")), t)
    cards.setdefault(norm(t["name"]), t)
for b in get("cards_stats_building.json"):
    buildings.setdefault(norm(b.get("name_en")), b)
    buildings.setdefault(norm(b["name"]), b)
cards.pop("", None)
buildings.pop("", None)

rows, missing, report = [], [], []
for cid, info in sorted(sc.engine_cards().items()):
    if info["is_spell"] or info["evolution"]:
        continue
    n = norm(info["name"])
    n = n[4:] if info["is_hero"] and n.startswith("hero") else n
    t = cards.get(n)
    ch = chars.get(t["summon_character"]) if t else buildings.get(n)
    if not ch or not ch.get("hit_speed"):
        missing.append(info["name"])
        continue
    load = ch.get("load_time") or 0
    rows.append((cid, info["name"], round(load / 100), ch["name"], load, ch["hit_speed"]))
lines = [
    "#pragma once",
    "",
    "// First-hit delay (load time) per card, in ticks: the windup before a unit's",
    "// first hit on a target, and before every hit after a retarget. Generated by",
    "// bot-77's scripts/sim_load_times.py from RoyaleAPI cr-api-data (public",
    "// game-file extracts, last updated 2023-12): cards_stats_troop.json's",
    "// summon_character -> cards_stats_characters.json / cards_stats_building.json",
    "// load_time (ms). Cards not listed (spells, evolutions, unmatched) have none.",
    "inline int loadTicksForCard(int cardId) {",
    "    switch (cardId) {",
]
lines += [f"        case {cid}: return {ticks};  // {name} ({char}: {load} ms of {hs} ms)" for cid, name, ticks, char, load, hs
          in rows]
lines += ["        default: return 0;", "    }", "}", ""]
OUT.write_text("\n".join(lines))
print(f"{len(rows)} cards with a load time -> {OUT}; unmatched: {missing}")
