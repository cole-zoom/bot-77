"""Spells' (and the Miner's) crown-tower damage for the simulator engine -> the fork's include/core/SpellTowerDamage.h
(docs/simulator-card-audit.md, 2026-10-24).

  uv run python scripts/sim_spell_tower.py

The engine's spells hit crown towers for 100% of their damage (Fireball 689); the game deals a published fraction
(Fireball, Arrows, Zap: 30%; Rocket 25%; The Log 20%). The fraction per spell comes from RoyaleAPI cr-api-data
(`crown_tower_damage_percent` on the spell or its projectile; data/external/cr-api-data, see scripts/sim_load_times.py).
Spells without a published reduction (none, or 0 in this 2023 extract) are left as the engine has them, and listed.
"""
import json
import re
from pathlib import Path

from bot77.sim import cards as sc

D = Path("data/external/cr-api-data")
OUT = Path("third_party/clash-royale-env/include/core/SpellTowerDamage.h")
ALIASES = {"thelog": "LogProjectileRolling", "barbarianbarrel": "BarbLogProjectileRolling",
           "giantsnowball": "SnowballSpell", "lightning": "LighningSpell"}  # (sic: the data's spelling)


def norm(s):
    return re.sub(r"[^a-z]", "", (s or "").lower())


spells = json.loads((D / "cards_stats_spell.json").read_text())
projs = {p["name"]: p for p in json.loads((D / "cards_stats_projectile.json").read_text())}
by = {}
for s in spells:
    for k in (norm(s.get("name_en")), norm(s["name"])):
        if k:
            by.setdefault(k, s)

rows, missing = [], []
for cid, info in sorted(sc.engine_cards().items()):
    if not info["is_spell"]:
        continue
    n = norm(info["name"])
    cands = [by.get(n), projs.get(ALIASES.get(n, "")), projs.get(info["name"].replace(" ", "") + "Spell")]
    if by.get(n) and by[n].get("projectile") in projs:
        cands.insert(1, projs[by[n]["projectile"]])
    pct = next((c["crown_tower_damage_percent"] for c in cands if c and c.get("crown_tower_damage_percent")), None)
    if not pct:  # nothing published, or 0 (left as the engine has it: Lightning, Earthquake, ... may be stale data)
        missing.append(info["name"])
        continue
    rows.append((cid, info["name"], 1 + pct / 100, pct))

# troops with a published Crown Tower reduction (the Miner): their direct hits on a tower
chars = {c["name"]: c for c in json.loads((D / "cards_stats_characters.json").read_text())}
troops = {}
for t in json.loads((D / "cards_stats_troop.json").read_text()):
    troops.setdefault(norm(t.get("name_en")), t)
for cid, info in sorted(sc.engine_cards().items()):
    if info["is_spell"] or info["evolution"]:
        continue
    t = troops.get(norm(info["name"]))
    pct = (chars.get(t["summon_character"]) or {}).get("crown_tower_damage_percent") if t else None
    if pct and pct < 0:
        rows.append((cid, info["name"], 1 + pct / 100, pct))

lines = ["#pragma once", "",
         "// The fraction of a spell's (or a troop's direct hit's) damage it deals to a Crown Tower. Generated by bot-77's",
         "// scripts/sim_spell_tower.py from RoyaleAPI cr-api-data (crown_tower_damage_percent, 2023-12).",
         "// -1 for spells without a published value (they keep 100%).",
         "inline float crownTowerFractionForCard(int cardId) {", "    switch (cardId) {"]
lines += [f"        case {cid}: return {frac:.2f}f;  // {name} ({pct:+d}%)" for cid, name, frac, pct in rows]
lines += ["        default: return -1.0f;", "    }", "}", ""]
OUT.write_text("\n".join(lines))
print(f"{len(rows)} spells with a crown-tower fraction -> {OUT}; none published for: {missing}")
for r in rows:
    print(f"  {r[1]}: {r[2]:.2f}")
