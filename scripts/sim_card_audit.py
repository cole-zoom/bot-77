"""Every engine card's stats against RoyaleAPI cr-api-data at level 11 (the level the engine's cards are at) ->
docs/simulator-card-audit.md (docs/simulator.md S2 follow-up, 2026-10-24).

  uv run python scripts/sim_card_audit.py

Troops / buildings: hp, damage (the character's, or its projectile's), hit speed, range, bodies. Spells: damage and
crown-tower damage. Data: data/external/cr-api-data/ (downloaded by scripts/sim_load_times.py; public game-file
extracts, last updated 2023-12: cards changed since then show up here too, so a mismatch is a lead, not a verdict).
"""
import json
import re
from pathlib import Path

import clash_royale_env as cre

from bot77.sim import cards as sc

D = Path("data/external/cr-api-data")
LEVEL = 11
START = {"Common": 1, "Rare": 3, "Epic": 6, "Legendary": 9, "Champion": 11}  # each rarity's per-level list starts here
TOL = 0.05


def load(name):
    p = D / name
    if not p.exists():
        import urllib.request
        urllib.request.urlretrieve("https://royaleapi.github.io/cr-api-data/json/" + name, p)
    return json.loads(p.read_text())


def norm(s):
    return re.sub(r"[^a-z]", "", (s or "").lower())


chars = {c["name"]: c for c in load("cards_stats_characters.json") + load("cards_stats_building.json")}
projs = {p["name"]: p for p in load("cards_stats_projectile.json")}
spells = {}
for s in load("cards_stats_spell.json"):
    spells.setdefault(norm(s.get("name_en")), s)
    spells.setdefault(norm(s["name"]), s)
troops = {}
for t in load("cards_stats_troop.json"):
    troops.setdefault(norm(t.get("name_en")), t)
    troops.setdefault(norm(t["name"]), t)
buildings = {}
for b in load("cards_stats_building.json"):
    buildings.setdefault(norm(b.get("name_en")), b)
    buildings.setdefault(norm(b["name"]), b)


def lvl(v, rarity):
    if isinstance(v, list) and v:
        return v[max(0, min(LEVEL - START.get(rarity or "Common", 1), len(v) - 1))]
    return v


rows, unmatched = [], []
for cid, info in sorted(sc.engine_cards().items()):
    if info["evolution"] or info["is_hero"]:
        continue
    st = cre.get_card_stats(cid)
    n = norm(info["name"])
    if info["is_spell"]:
        s = spells.get(n)
        if not s or not (s.get("damage_per_level") or s.get("damage")):  # projectile spells: Arrows -> ArrowsSpell
            s = next((p for k, p in projs.items() if norm(k) in (n + "spell", n + "projectilerolling")
                      and p.get("damage_per_level")), s)
        if not s:
            unmatched.append(info["name"])
            continue
        dmg = lvl(s.get("damage_per_level"), s.get("rarity")) or s.get("damage")
        ct = s.get("crown_tower_damage_percent")
        rows.append((info["name"], "spell", [
            ("damage", st["damage"], dmg),
            ("crown tower damage", st["spell_crown_tower_damage"] if st["spell_crown_tower_damage"] >= 0 else st["damage"],
             round(dmg * (1 + ct / 100)) if (dmg and ct is not None) else None),
        ]))
        continue
    t = troops.get(n)
    ch = chars.get(t["summon_character"]) if t else buildings.get(n)
    if not ch:
        unmatched.append(info["name"])
        continue
    rar = ch.get("rarity") or (t or {}).get("rarity")
    dmg = lvl(ch.get("damage_per_level"), rar)
    if not dmg and ch.get("projectile") in projs:
        pr = projs[ch["projectile"]]
        dmg = lvl(pr.get("damage_per_level"), pr.get("rarity") or rar) or pr.get("damage")
    rng = (ch.get("range") or 0) / 1000
    rows.append((info["name"], "building" if info["is_building"] else "troop", [
        ("hp", st["hp"], lvl(ch.get("hitpoints_per_level"), rar)),
        ("damage", st["damage"], dmg),
        ("hit speed (s)", st["attack_cooldown"] / 10, (ch.get("hit_speed") or 0) / 1000 or None),
        ("range", round(st["attack_range"], 2), rng or None),
        ("bodies", st["bodies"], (t or {}).get("summon_number") or None),
    ]))

off = []
for name, kind, checks in rows:
    for what, eng, real in checks:
        if real in (None, 0) or eng in (None,):
            continue
        if abs(eng - real) / abs(real) > TOL:
            off.append((name, kind, what, eng, real, (eng - real) / real))
off.sort(key=lambda r: -abs(r[5]))
lines = ["# Simulator card audit (generated by `scripts/sim_card_audit.py`)", "",
         f"Engine stats (`get_card_stats`) vs RoyaleAPI cr-api-data at level 11 (2023-12 extract). {len(rows)} cards "
         f"checked, {len(off)} values more than {TOL:.0%} off. Ranges in tiles (melee reach conventions differ between the "
         "two, so small range gaps on melee units are expected). Unmatched (newer than the data, or named differently): "
         f"{', '.join(unmatched) or 'none'}.", "", "| Card | Kind | Stat | Engine | Data | Off |", "|---|---|---|---|---|---|"]
lines += [f"| {n} | {k} | {w} | {e} | {r} | {d:+.0%} |" for n, k, w, e, r, d in off]
Path("docs/simulator-card-audit.md").write_text("\n".join(lines) + "\n")
print("\n".join(lines[:60]))
